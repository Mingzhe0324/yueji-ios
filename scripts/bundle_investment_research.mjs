// Generates a single pasteable dashboard entry point without embedding secrets.
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const base=path.join(root,'supabase/functions/investment-research');
const modules=[['official.mjs',['officialSources','collectOfficialEvidence','evidencePrompt','evidenceReport']],
 ['cache.mjs',['reportKey','validCachedReport']],['handler.mjs',['handleResearch']]];
let output='// Generated by scripts/bundle_investment_research.mjs. No secrets included.\n';
for(const [file,names] of modules){
 const code=(await readFile(path.join(base,file),'utf8')).replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
 output+=`\nconst { ${names.join(', ')} } = (() => {\n${code}\nreturn { ${names.join(', ')} };\n})();\n`;
}
output+='\nDeno.serve(request => handleResearch(request, {env: name => Deno.env.get(name), fetch}));\n';
const destination=path.resolve(root,'../builds/investment-research-deploy');
await mkdir(destination,{recursive:true});
await writeFile(path.join(destination,'index.ts'),output);
await writeFile(path.join(destination,'syntax-check.mjs'),output);
const sql=(await readFile(path.join(root,'backend/investment-research.sql'),'utf8'))+'\n'+(await readFile(path.join(root,'backend/investment-research-cache.sql'),'utf8'));
await writeFile(path.join(destination,'database.sql'),sql);
console.log(`Prepared ${destination}: index.ts and database.sql; configure secrets separately.`);
